CREATE TABLE IF NOT EXISTS hatti_products (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug text NOT NULL UNIQUE,
  name text NOT NULL,
  category text NOT NULL CHECK (category IN ('Футболки', 'Обложки', 'Чехлы', 'Кепки')),
  color text NOT NULL,
  image text NOT NULL,
  code text NOT NULL,
  description text NOT NULL,
  sizes text[],
  models text[],
  -- Nullable until migration 002 backfills existing covers and the current id order.
  images jsonb,
  sort_order integer,
  price numeric(14,2) CHECK (price > 0),
  old_price numeric(14,2) CHECK (old_price > 0),
  currency text NOT NULL DEFAULT 'RUB' CHECK (currency IN ('RUB', 'USD', 'EUR', 'TRY')),
  price_from boolean NOT NULL DEFAULT false,
  show_price boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT hatti_products_options_check CHECK (sizes IS NULL OR models IS NULL)
);

CREATE TABLE IF NOT EXISTS hatti_media (
  filename text PRIMARY KEY,
  content_type text NOT NULL CHECK (content_type IN ('image/png', 'image/jpeg', 'image/webp')),
  bytes bytea NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hatti_catalog_meta (
  key text PRIMARY KEY,
  value text NOT NULL
);

ALTER TABLE hatti_products ENABLE ROW LEVEL SECURITY;
ALTER TABLE hatti_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE hatti_catalog_meta ENABLE ROW LEVEL SECURITY;

