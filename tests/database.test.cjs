require("./register.cjs");
const { test } = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { Pool } = require("pg");

test("PostgreSQL legacy migration, repeatability, rollback and concurrent ordering", { skip: !process.env.TEST_DATABASE_URL }, async () => {
  const connection = new URL(process.env.TEST_DATABASE_URL);
  assert.equal(connection.hostname, "127.0.0.1", "Integration tests only accept an isolated localhost database.");
  const admin = new Pool({ connectionString: connection.href });
  const name = `hatti_checks_${Date.now()}`;
  await admin.query(`CREATE DATABASE ${name}`);
  connection.pathname = `/${name}`;
  process.env.DATABASE_URL = connection.href;
  const legacy = new Pool({ connectionString: connection.href });
  try {
    await legacy.query(`CREATE TABLE hatti_products (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, slug text NOT NULL UNIQUE, name text NOT NULL,
      category text NOT NULL, color text NOT NULL, image text NOT NULL, code text NOT NULL, description text NOT NULL,
      sizes text[], models text[], created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now());
      INSERT INTO hatti_products (id, slug, name, category, color, image, code, description)
      VALUES (5, 'legacy-five', 'Пятый', 'Футболки', 'Чёрный', '/products/05_blue_roses_tshirt_white.png', '5', 'Старое описание'),
        (2, 'legacy-two', 'Второй', 'Футболки', 'Белый', '/products/02_green_patch_tshirt_white.png', '2', 'Старое описание');
      SELECT setval(pg_get_serial_sequence('hatti_products', 'id'), 5, true);`);
    const db = require("../lib/database.ts");
    let products = await db.databaseProducts();
    assert.deepEqual(products.map((p) => p.id), [2, 5]);
    assert.deepEqual(products.map((p) => p.sort_order), [0, 1]);
    assert.equal(products[0].images[0].src, products[0].image);
    assert.equal(products[0].price, null);
    const input = { ...products[0], images: [{ src: products[1].image, alt: "Новая обложка" }], image: products[1].image, price: 12500, old_price: 15000 };
    await db.databaseSaveProduct(2, input);
    await db.databaseReorderProducts([5, 2]);
    const created = await Promise.all([db.databaseCreateProduct(input), db.databaseCreateProduct(input)]);
    assert.equal(new Set(created.map((p) => p.sort_order)).size, 2);
    products = await db.databaseProducts();
    assert.deepEqual(products.map((p) => p.sort_order), [0, 1, 2, 3]);
    assert.equal(products[1].price, 12500);
    assert.equal(products[1].images[0].alt, "Новая обложка");
    const before = JSON.stringify(products);
    await assert.rejects(db.databaseReorderProducts([5, 2]));
    assert.equal(JSON.stringify(await db.databaseProducts()), before);
    const migration = await fs.readFile(path.join(__dirname, "..", "db", "migrations", "002_product_gallery_order_price.sql"), "utf8");
    await legacy.query(migration);
    await legacy.query(migration);
    assert.equal(JSON.stringify(await db.databaseProducts()), before);
    await assert.rejects(legacy.query("UPDATE hatti_products SET price = -1 WHERE id = 2"));
    await assert.rejects(legacy.query("UPDATE hatti_products SET currency = 'XXX' WHERE id = 2"));
    assert.equal((await legacy.query("SELECT COUNT(*)::int AS count FROM hatti_products")).rows[0].count, 4);
  } finally {
    await legacy.end();
    const db = require("../lib/database.ts");
    await (await db.database()).end();
    await admin.end();
  }
});

test("fresh database can be manually migrated before initial catalog seeding", { skip: !process.env.TEST_DATABASE_URL }, async () => {
  const connection = new URL(process.env.TEST_DATABASE_URL);
  assert.equal(connection.hostname, "127.0.0.1");
  const admin = new Pool({ connectionString: connection.href });
  const name = `hatti_fresh_${Date.now()}`;
  await admin.query(`CREATE DATABASE ${name}`);
  connection.pathname = `/${name}`;
  const fresh = new Pool({ connectionString: connection.href });
  try {
    await fresh.query(await fs.readFile(path.join(__dirname, "..", "db", "schema.sql"), "utf8"));
    await fresh.query(await fs.readFile(path.join(__dirname, "..", "db", "migrations", "002_product_gallery_order_price.sql"), "utf8"));
    process.env.DATABASE_URL = connection.href;
    delete require.cache[require.resolve("../lib/database.ts")];
    const db = require("../lib/database.ts");
    const products = await db.databaseProducts();
    assert.equal(products.length, 20);
    assert.equal(products.every((p, i) => p.images.length === 1 && p.images[0].src === p.image && p.sort_order === i), true);
    await (await db.database()).end();
  } finally { await fresh.end(); await admin.end(); }
});
